// SSD1306 命令
#define OLED_CMD_DISPLAY_OFF      0xAE
#define OLED_CMD_DISPLAY_ON       0xAF
#define OLED_CMD_SET_MUX_RATIO    0xA8
#define OLED_CMD_SET_DISP_OFFSET  0xD3
#define OLED_CMD_SET_DISP_START   0x40
