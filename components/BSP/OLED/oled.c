esp_err_t oled_init(void)
{
    // SSD1306 初始化序列
    oled_write_cmd(OLED_CMD_DISPLAY_OFF);
    oled_write_cmd(OLED_CMD_SET_MUX_RATIO);
    oled_write_cmd(OLED_HEIGHT - 1);
    oled_write_cmd(OLED_CMD_SET_DISP_OFFSET);
    oled_write_cmd(0x00);
    oled_write_cmd(OLED_CMD_SET_DISP_START);       // 显示起始行
    oled_write_cmd(OLED_CMD_SET_SEG_REMAP);        // 列重映射 (左右翻转)
    oled_write_cmd(OLED_CMD_SET_COM_SCAN_DIR);     // COM 扫描方向 (上下翻转)
    oled_write_cmd(OLED_CMD_SET_COM_PINS);
    oled_write_cmd(0x12);                          // 128x64 模式
    oled_write_cmd(OLED_CMD_SET_CONTRAST);
    oled_write_cmd(0x7F);
    oled_write_cmd(OLED_CMD_DISP_NORMAL);
    oled_write_cmd(OLED_CMD_SET_OSC_FREQ);
    oled_write_cmd(0x80);
    oled_write_cmd(OLED_CMD_SET_CHARGE_PUMP);
    oled_write_cmd(0x14);                          // 使能电荷泵
    oled_write_cmd(OLED_CMD_SET_MEM_MODE);
    oled_write_cmd(0x00);                          // 水平寻址模式
    oled_write_cmd(OLED_CMD_DISPLAY_ON);

    ESP_LOGI(TAG, "SSD1306 OLED initialized");
    return ESP_OK;
}

void oled_clear(void)
{
    // 设置全屏写入范围
    oled_write_cmd(OLED_CMD_SET_COL_ADDR);
    oled_write_cmd(0);
    oled_write_cmd(OLED_WIDTH - 1);
    oled_write_cmd(OLED_CMD_SET_PAGE_ADDR);
    oled_write_cmd(0);
    oled_write_cmd(OLED_PAGES - 1);

    uint8_t zero[OLED_WIDTH];
    memset(zero, 0, OLED_WIDTH);
    for (int i = 0; i < OLED_PAGES; i++) {
        oled_write_data(zero, OLED_WIDTH);
    }
}

void oled_clear_line(uint8_t line)
{
    if (line >= OLED_PAGES) return;
    oled_write_cmd(OLED_CMD_SET_COL_ADDR);
    oled_write_cmd(0);
    oled_write_cmd(OLED_WIDTH - 1);
    oled_write_cmd(OLED_CMD_SET_PAGE_ADDR);
    oled_write_cmd(line);
    oled_write_cmd(line);

    uint8_t zero[OLED_WIDTH];
    memset(zero, 0, OLED_WIDTH);
    oled_write_data(zero, OLED_WIDTH);
}

void oled_show_text_xy(uint8_t x, uint8_t page, const char *text)
{
    if (page >= OLED_PAGES) return;

    oled_write_cmd(OLED_CMD_SET_COL_ADDR);
    oled_write_cmd(x);
    oled_write_cmd(OLED_WIDTH - 1);
    oled_write_cmd(OLED_CMD_SET_PAGE_ADDR);
    oled_write_cmd(page);
    oled_write_cmd(page);

    uint8_t buf[OLED_WIDTH];
    size_t buf_idx = 0;
    while (*text && buf_idx + 6 <= OLED_WIDTH - x) {
        uint8_t ch = (uint8_t)*text;
        if (ch < 32 || ch > 126) ch = 32;
        const uint8_t *glyph = font6x8[ch - 32];
        for (int i = 0; i < 6; i++) {
            buf[buf_idx++] = glyph[i];
        }
        text++;
    }
    // 用空格填充剩余
    while (buf_idx < OLED_WIDTH) {
        buf[buf_idx++] = 0;
    }
    oled_write_data(buf, OLED_WIDTH);
}

void oled_show_text(uint8_t line, const char *text)
{
    oled_show_text_xy(0, line, text);
}
